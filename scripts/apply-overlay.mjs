#!/usr/bin/env node
// Build api/openapi.yaml: the spec Salesforce generated (api/source/openapi.json)
// with every overlay in api/overlay/ applied, in file name order.
//
// Supports the OpenAPI Overlay 1.0 `update` and `remove` actions with simple
// targets: $, .key and ['key'] segments (no wildcards or filters). A target that
// matches nothing fails the build, so an overlay never silently stops applying
// after Salesforce changes the spec.
//
// Usage: node scripts/apply-overlay.mjs [--check]
//   --check  exit 1 if api/openapi.yaml is not up to date (used by the PR gate)
import fs from "node:fs";
import path from "node:path";
import yaml from "js-yaml";
import { repoRoot } from "./lib/env.mjs";

const sourcePath = path.join(repoRoot, "api", "source", "openapi.json");
const overlayDir = path.join(repoRoot, "api", "overlay");
const outputPath = path.join(repoRoot, "api", "openapi.yaml");

function parseTarget(target) {
  if (!target.startsWith("$")) throw new Error(`target must start with $: ${target}`);
  const keys = [];
  const re = /\.([A-Za-z0-9_-]+)|\['([^']+)'\]/gy;
  re.lastIndex = 1;
  while (re.lastIndex < target.length) {
    const m = re.exec(target);
    if (!m) throw new Error(`unsupported target syntax: ${target}`);
    keys.push(m[1] ?? m[2]);
  }
  return keys;
}

function deepMerge(into, from) {
  for (const [key, value] of Object.entries(from)) {
    if (value && typeof value === "object" && !Array.isArray(value) && into[key] && typeof into[key] === "object") {
      deepMerge(into[key], value);
    } else {
      into[key] = value;
    }
  }
}

const spec = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const overlays = fs.existsSync(overlayDir)
  ? fs.readdirSync(overlayDir).filter((f) => /\.ya?ml$/.test(f)).sort()
  : [];

let applied = 0;
for (const file of overlays) {
  const overlay = yaml.load(fs.readFileSync(path.join(overlayDir, file), "utf8"));
  for (const action of overlay.actions ?? []) {
    const keys = parseTarget(action.target);
    let parent = null;
    let node = spec;
    for (const key of keys) {
      parent = node;
      node = node?.[key];
    }
    if (node === undefined) {
      console.error(`apply-overlay: ${file}: target matches nothing: ${action.target}`);
      process.exit(1);
    }
    if (action.remove) {
      if (!parent) throw new Error(`${file}: cannot remove the root`);
      delete parent[keys.at(-1)];
    } else if (action.update) {
      deepMerge(node, action.update);
    }
    applied++;
  }
}

const header =
  "# GENERATED by scripts/apply-overlay.mjs: api/source/openapi.json + api/overlay/*.yaml.\n" +
  "# Do not edit. Run `make build` after regenerating the spec or changing an overlay.\n";
const built = header + yaml.dump(spec, { lineWidth: -1, noRefs: true });

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== built) {
    console.error("apply-overlay: api/openapi.yaml is out of date; run `make build` and commit the result");
    process.exit(1);
  }
  console.log(`apply-overlay: api/openapi.yaml is up to date (${applied} overlay actions)`);
} else {
  fs.writeFileSync(outputPath, built);
  console.log(`apply-overlay: wrote api/openapi.yaml (${applied} actions from ${overlays.length} overlay file(s))`);
}
